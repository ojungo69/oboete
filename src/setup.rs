fn pi_files(dir: &Path, cmd: &HookCommand, remove: bool) -> Result<Vec<String>> {
    let file = dir.join("extensions/oboete.ts");
    let old = read_text(&file)?;
    if remove {
        if !old.starts_with(PI_MARKER) {
            return Ok(Vec::new());
        }
        refuse_read_only(&file)?;
        std::fs::remove_file(&file).with_context(|| format!("remove {}", file.display()))?;
    } else {
        let text = pi_extension(cmd)?;
        if old == text {
            return Ok(Vec::new());
        }
        let staged = stage(&file, &text)?;
        backup_once(&file)?;
        staged.commit()?;
    }
    Ok(vec![file.display().to_string()])
}

